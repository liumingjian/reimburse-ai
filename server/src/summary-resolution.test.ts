import { randomBytes } from 'node:crypto';
import { join } from 'node:path';
import { tempDataDir, testClient } from './test/harness';
import { presetParser } from './test/parse-presets';
import ExcelJS from 'exceljs';
import { PairingViewSchema, PairingTokenSchema, PAIRING_PATH, EXECUTOR_VERSION } from '@baox/contract';
import { fakeLocalExecutor } from './erp/testing/fake-local-executor';
import type { TestClient } from './test/harness';
async function pair(client: TestClient) {
  const issued = PairingViewSchema.parse(await (await client.post('/api/pairing/code', {})).json());
  const redeemed = await server.app.request(PAIRING_PATH, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ code: issued.code, browser: 'test', version: EXECUTOR_VERSION }) });
  return PairingTokenSchema.parse(await redeemed.json()).token;
}
import { afterEach, expect, it } from 'vitest';
import { scenario, scenarioServer, type ScenarioServer, type ScenarioServerOptions } from './test/scenario';
let server: ScenarioServer;
afterEach(() => server?.close());
it.each(['voucher', 'stay'])('resolves %s first and preserves the other blocker and confirmed evidence', async first => {
  const preset = presetParser();
  const dataDir = tempDataDir();
  const options = { dataDir, database: join(dataDir, 'summary.sqlite'), erpCredentialKey: randomBytes(32), erpExecutor: 'paired', parser: {
    async parse(input) {
      const result = await preset.parse(input);
      if (result.outcome === 'recognised') for (const candidate of result.candidates) {
        if (candidate.key === 'segments[1].city') candidate.value = '杭州';
        if (candidate.key === 'checkOut') candidate.value = '2026-08-09';
        if (candidate.key === 'segments[0].amount') candidate.value = '10.20';
        if (candidate.key === 'segments[1].amount') candidate.value = '20.30';
        if (candidate.key === 'segmentCount') candidate.value = '2';
        if (candidate.key === 'itineraryTotal') candidate.value = '30.50';
        if (['totalAmount','netAmount'].includes(candidate.key) && ['69.19','67.18'].includes(candidate.value)) candidate.value = '30.50';
        if (candidate.key === 'taxAmount') candidate.value = '0.00';
      }
      if (result.outcome === 'recognised') result.candidates = result.candidates.filter(candidate => !candidate.key.startsWith('segments[2].'));
      return result;
    }, close: async () => {},
  } } satisfies ScenarioServerOptions;
  server = await scenarioServer(options);
  let scene = await scenario(server).at('actions', { materials: ['m01','m02','m03','m04'], homeCity: '上海' });
  const initial = scene.reached;
  const summary = initial.reimbursementSummary;
  expect(summary.status).toBe('unavailable');
  if (summary.status !== 'unavailable' || !summary.inputs) throw new Error('missing resolution inputs');
  expect(summary.inputs.map(input => input.kind).sort()).toEqual(['stay-days','voucher-count']);
  const revision = summary.confirmationRevision;
  const voucher = summary.inputs.find(input => input.kind === 'voucher-count')!;
  const stay = summary.inputs.find(input => input.kind === 'stay-days')!;
  if (voucher.kind !== 'voucher-count' || stay.kind !== 'stay-days') throw new Error('wrong inputs');
  expect(await scene.refused('generate-reimbursement-summary')).toEqual({ status: 400, code: 'summary_inputs_unresolved' });
  expect(await scene.refused('resolve-reimbursement-summary', { confirmationRevision: revision, voucherCounts: [{ voucherMaterialId: voucher.voucherMaterialId, category: '住宿' }] })).toEqual({ status: 400, code: 'invalid_summary_resolution' });
  for (const days of [-1, 1.5]) expect((await scene.refused('resolve-reimbursement-summary', { confirmationRevision: revision, stayDays: [{ lineId: stay.lineId, days }] })).status).toBe(400);
  expect(await scene.refused('resolve-reimbursement-summary', { confirmationRevision: revision, stayDays: [{ lineId: 'other-stay', days: 1 }] })).toEqual({ status: 400, code: 'invalid_summary_resolution' });
  expect(await scene.refused('resolve-reimbursement-summary', { confirmationRevision: revision! + 1, stayDays: [{ lineId: stay.lineId, days: 1 }] })).toEqual({ status: 400, code: 'stale_summary_resolution' });
  expect((await scene.snapshot()).confirmation).toEqual(initial.confirmation);
  const countChoice = { confirmationRevision: revision, voucherCounts: [{ voucherMaterialId: voucher.voucherMaterialId, category: '外地市内交通' }] };
  const stayChoice = { confirmationRevision: revision, stayDays: [{ lineId: stay.lineId, days: 1 }] };
  const partial = await scene.accept('resolve-reimbursement-summary', first === 'voucher' ? countChoice : stayChoice);
  expect(partial.reimbursementSummary).toMatchObject({ status: 'unavailable', inputs: [{ kind: first === 'voucher' ? 'stay-days' : 'voucher-count' }] });
  expect(await scene.refused('generate-reimbursement-summary')).toEqual({ status: 400, code: 'summary_inputs_unresolved' });
  const identity = scene.client;
  const taskId = scene.task.taskId;
  await server.app.close(); await server.db.destroy();
  server = await scenarioServer(options);
  scene = await scenario(server, testClient(server.app, identity.account, identity.cookie)).of(taskId);
  expect((await scene.snapshot()).reimbursementSummary).toEqual(partial.reimbursementSummary);
  const ready = await scene.accept('resolve-reimbursement-summary', first === 'voucher' ? stayChoice : countChoice);
  expect(ready.reimbursementSummary.status).toBe('ready');
  expect(ready.confirmation).toEqual(initial.confirmation);
  expect(ready.lines).toEqual(initial.lines);
  const local = fakeLocalExecutor(server.app.executorHub, await pair(scene.client), { trySignIn: async () => ({ ok: true, employeeProfile: { status: 'ready', erpAccount: 'synthetic', tenant: 'test', name: '测试员工', department: '测试部门' } }) });
  await local.connect();
  await server.authoriseErpCredentials(scene.client.account.accountId, { account: 'synthetic', password: 'test-password' });
  const generated = (await scene.accept('generate-reimbursement-summary')).reimbursementSummary;
  if (generated.status !== 'generated') throw new Error('missing workbook');
  const workbook = new ExcelJS.Workbook(); await workbook.xlsx.load(await (await scene.client.request(generated.url)).arrayBuffer());
  const sheet = workbook.worksheets[0]!;
  expect(['F7','F8','D7','D8','E6'].map(cell => sheet.getCell(cell).value)).toEqual([10.2,20.3,0,1,1]);
  expect(generated.data.totalVouchers).toBe(2);
  expect((await scene.accept('generate-reimbursement-summary')).reimbursementSummary).toEqual(generated);
  await scene.accept('resolve-reimbursement-summary', { confirmationRevision: revision, stayDays: [{ lineId: stay.lineId, days: 0 }] });
  expect((await scene.client.request(generated.url)).status).toBe(404);
  const zero = (await scene.accept('generate-reimbursement-summary')).reimbursementSummary;
  if (zero.status !== 'generated') throw new Error('missing explicit zero workbook');
  const zeroWorkbook = new ExcelJS.Workbook(); await zeroWorkbook.xlsx.load(await (await scene.client.request(zero.url)).arrayBuffer());
  expect(zeroWorkbook.worksheets[0]!.getCell('E6').value).toBe(0);
  expect((await scene.snapshot()).lines).toEqual(initial.lines);
  expect((await scene.snapshot()).confirmation).toEqual(initial.confirmation);
  const changed = await scene.accept('set-home-city', { homeCity: '杭州' });
  const reassigned = await scene.accept('submit-project-assignment', { purpose: '测试出差', projects: Object.fromEntries(changed.lines.map(line => [line.lineId, 'P-2307'])) });
  const reconfirmed = await scene.accept('confirm-review', { digest: reassigned.confirmation.digest });
  expect(reconfirmed.reimbursementSummary).toMatchObject({ status: 'unavailable', inputs: expect.arrayContaining([{ kind: 'stay-days', lineId: stay.lineId, label: stay.label, date: stay.date }]) });
  if (reconfirmed.reimbursementSummary.status !== 'unavailable') throw new Error('missing renewed inputs');
  expect(reconfirmed.reimbursementSummary.inputs).toHaveLength(2);
  expect(await scene.refused('resolve-reimbursement-summary', stayChoice)).toEqual({ status: 400, code: 'stale_summary_resolution' });
  await scene.accept('reopen-upload');
  expect((await scene.client.request(generated.url)).status).toBe(404);
  expect((await scene.refused('resolve-reimbursement-summary', { confirmationRevision: revision, stayDays: [{ lineId: stay.lineId, days: 1 }] })).status).toBe(400);
  local.disconnect();
});
